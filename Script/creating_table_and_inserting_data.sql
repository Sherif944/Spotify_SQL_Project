)

SELECT
	Artist,
	Track,
	Album,
	Album_type,
	CAST(Danceability AS FLOAT),
	CAST(Energy AS FLOAT),
	CAST(Loudness AS FLOAT),
	CAST(Speechiness AS FLOAT),
	CAST(Acousticness AS FLOAT),
	CAST(Instrumentalness AS FLOAT),
	CAST(Liveness AS FLOAT),
	CAST(Valence AS FLOAT),
	CAST(Tempo AS FLOAT),
	CAST(Duration_min AS FLOAT),
	Title,
	Channel,
	CAST(Views AS BIGINT),
	CAST(Likes AS BIGINT),
	CAST(Comments AS BIGINT),
	Licensed,
	official_video,
	CAST(Stream AS BIGINT),
	CAST(EnergyLiveness AS FLOAT),
	most_playedon
FROM spotify
