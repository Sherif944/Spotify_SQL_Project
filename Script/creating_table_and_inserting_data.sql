/* This script will create a table called spotify_tbl
if the table exists already the query will drop it immediately*/

DROP TABLE IF EXISTS spotify_tbl
CREATE TABLE spotify_tbl(
[Artist] NVARCHAR(MAX),
[Track] NVARCHAR(MAX),
[Album] NVARCHAR(MAX),
[Album_type] NVARCHAR(MAX),
[Danceability] FLOAT,
[Energy] FLOAT,
[Loudness] FLOAT,
[Speechiness] FLOAT,
[Acousticness] FLOAT,
[Instrumentalness] FLOAT,
[Liveness] FLOAT,
[Valence] FLOAT,
[Tempo] FLOAT,
[Duration_min] FLOAT,
[Title] NVARCHAR(MAX),
[Channel] NVARCHAR(MAX),
[Views] BIGINT,
[Likes] BIGINT,
[Comments] BIGINT,
[Licensed] NVARCHAR(MAX),
[official_video] NVARCHAR(MAX),
[Stream] BIGINT,
[EnergyLiveness] FLOAT,
[most_playedon] NVARCHAR(MAX)
)

INSERT INTO spotify_tbl(
[Artist],
[Track],
